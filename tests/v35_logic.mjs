import assert from 'node:assert/strict';
import {CONTENT} from '../content.mjs';
import {CONFIG} from '../balance-config.mjs';
import {A} from '../numbers.mjs';
import {PROPOSED, PLANET_EFFECT_PROPOSALS, FIRST_CONCEPT_PROPOSALS,resourcePrototype,trialResourceWeights, naturalGrowthFactors,boostTrialCost,proposedSourceSlots,trialPreview} from '../design-proposals.mjs';
import {createState,advance,invest,createPlanet,planet,trialEnabled,setTrialEnabled,validateState,distributeTrialResources,boostValues,labBoostUpgrade} from '../game.mjs';
import {encode,decode,KEYS} from '../save.mjs';
let checks=0;function test(cond,message){assert.ok(cond,message);checks++;}
const timestamp=Date.now();
test(/^3\./.test(CONFIG.version),'version');
test(CONFIG.schemaVersion===31,'schema unchanged');
test(KEYS.normal==='kotowari_v31_normal','save key unchanged');
test(KEYS.lab==='kotowari_v31_lab','lab save key unchanged');
test(CONFIG.unresolved.resourceReceipt===null,'unresolved resource receipt');
test(CONFIG.unresolved.pressureUnit===null,'unresolved pressure');
test(CONFIG.unresolved.conceptLevel2Cost===null,'unresolved concept');
test(CONTENT.concepts.length===77,'77 concepts');
test(CONTENT.sources.length===30,'30 sources');
test(CONTENT.resources.length===42,'42 resources');
test(CONTENT.stats.length===15,'15 stats');
test(CONTENT.sources.every(s=>s.effects.every(e=>e===null)),'all source approved effects remain null');
test(PLANET_EFFECT_PROPOSALS.length===7,'7 candidate planet stats');
test(FIRST_CONCEPT_PROPOSALS.length===12,'12 concept ideas');
test(CONTENT.sources.every(s=>proposedSourceSlots(s).length===7),'30x7 source slots');
test(PROPOSED.sourceSlots.every(n=>CONFIG.confirmed.sourceMilestones.includes(n)),'7 are among 21 confirmed milestones');
const trialProfiles=CONTENT.resources.map(resourcePrototype);
test(trialProfiles.every(x=>x?.stat&&x?.perUnit>0),'42 candidate resource profiles');
test(new Set(trialProfiles.slice(0,15).map(x=>x.stat+'-'+(x.stat2||''))).size===15,'15 distinct R1 specializations');
const normal=createState(timestamp,'normal');normal.intro.complete=true;normal.universe.unlocked=true;
test(!trialEnabled(normal),'normal trial disabled');
test(setTrialEnabled(normal,true).ok===false,'normal trial cannot activate');
const v=createPlanet(normal,timestamp);test(v.ok,'normal planet created');
normal.universe.resources.UR1_01='2';
const normalBefore=planet(normal).stats.density;const result=invest(normal,'UR1_01',1);
test(result.ok && result.trialSpecial===null,'normal invest unchanged');
test(planet(normal).stats.density===normalBefore,'normal density unchanged');
test(A(planet(normal).stats.mass).cmp(2)===0,'normal common mass +1');
test(decode(encode(normal,'qa'),'normal').trial.enabled===false,'normal save roundtrip');
const lab=createState(timestamp,'lab');lab.intro.complete=true;lab.universe.unlocked=true;
test(setTrialEnabled(lab,true).ok===true,'lab activate');
test(trialEnabled(lab),'lab trial active');
createPlanet(lab,timestamp);
lab.universe.resources.UR1_01='100';lab.universe.resources.UR1_15='100';lab.universe.resources.UR1_07='100';lab.universe.resources.UR1_05='100';
let ret=invest(lab,'UR1_01',10);test(ret.ok && ret.trialSpecial.stat==='density','lab density invest');
test(Math.abs(A(planet(lab).stats.density).toNumber()-1.8)<1e-9,'density amount');
ret=invest(lab,'UR1_15',10);test(ret.ok && ret.trialSpecial.stat==='energy','lab dual investment');
test(Math.abs(A(planet(lab).stats.temperature).toNumber()-.9)<1e-9,'dual temp');
ret=invest(lab,'UR1_07',10);test(ret.ok,'gravity investment');
ret=invest(lab,'UR1_05',10);test(ret.ok,'activity investment');
const facts=naturalGrowthFactors(planet(lab).stats);test(facts.gravity>=1&&facts.activity>=1,'bounded natural growth');
lab.lastWall=timestamp;const beforeMass=A(planet(lab).stats.mass).toNumber();advance(lab,timestamp+10000,{offline:false});
test(A(planet(lab).stats.mass).toNumber()>beforeMass,'natural mass growth');
test(trialPreview('density',100)>1,'density preview growth');
test(trialPreview('magnetism',500)<=1,'magnetism preview resistance');
test(naturalGrowthFactors({gravity:'999999999',activity:'999999999'}).gravity<=2,'gravity upper cap');
test(naturalGrowthFactors({gravity:'999999999',activity:'999999999'}).activity<=2,'activity upper cap');
const ids=CONTENT.resources.filter(r=>r.rank===1);
const weights=trialResourceWeights(ids,{temperature:'100'});
test(weights.length===15,'rank1 weight list');
test(weights.every(w=>w>=1),'nonnegative weights');
const draw=distributeTrialResources(100,ids,{temperature:100},()=>.1);
test(Object.entries(draw).every(([id])=>ids.some(x=>x.id===id)),'no unavailable resources');
test(Object.values(draw).reduce((a,b)=>a+A(b).toNumber(),0)===100,'draw count conserved');
test(Object.keys(distributeTrialResources(100,[],{},()=>0)).length===0,'no eligible resources, nothing generated');
const huge=distributeTrialResources('1e20',ids,{density:'0'},()=>.3);
test(Object.keys(huge).length===15,'large amounts are aggregate');
const before=encode(lab,'qa');test(decode(before,'lab').trial.enabled,'lab save retains toggle');
let legacy=structuredClone(lab);delete legacy.trial;test(validateState(legacy,'lab').trial.enabled===false,'old lab save loads with trial disabled');
test(setTrialEnabled(lab,false).ok && !trialEnabled(lab),'lab deactivation');
test(planet(lab).stats.density!=='0','switch off does not discard trial progress');
normal.trial.enabled=true;assert.throws(()=>validateState(normal,'normal'),/試案設定/);checks++;
const boosts=createState(timestamp,'lab');boosts.boost.seconds=3600;
test(boostTrialCost(0)===240,'boost initial cost');
test(boostTrialCost(10)>boostTrialCost(9),'boost grows');
test(boostTrialCost(19)<21600,'boost max cost affordable at 6h');
test(boostValues(boosts).efficiency===.3,'boost starting efficiency');
let br=labBoostUpgrade(boosts,0);test(br.ok&&boosts.boost.upgrades[0]===1,'lab boost trial purchases');
test(boostValues(boosts).efficiency>.3,'lab boost efficiency improves');
boosts.boost.upgrades[0]=PROPOSED.boost.limits[0];test(!labBoostUpgrade(boosts,0).ok,'boost cap effective');
test(boostValues(boosts).efficiency<=.86,'boost efficiency cap');
const normalBoost=boostValues(createState(timestamp,'normal'));
test(normalBoost.capacity===3600&&normalBoost.offlineCap===1800,'normal boost rules preserved');
console.log(`PASS ${checks} V3.5 logic, source/concept/content, lab isolation, save compatibility and economy checks`);
