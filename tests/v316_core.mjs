import assert from "node:assert/strict";
import {A} from "../numbers.mjs";
import {createState,createPlanet,planet,startCore,toggleAutoPlanet,setAutoPlanetReserve,advance,validateState} from "../game.mjs";
import {KNOWLEDGE_IDS,addKnowledge,knowledgeLevel,coreRequirements,makeCoreState,advanceCore,autoPlanetAvailable} from "../universe-progression-v316.mjs";
import {encode,decode} from "../save.mjs";
const now=1763600000000;
let checks=0;const test=(name,fn)=>{fn();checks++;console.log("✓",name);};
test("knowledge IDs and cap",()=>{
 const s=createState(now);
 assert.equal(KNOWLEDGE_IDS.length,8);
 assert.equal(knowledgeLevel(s.universe,"heat"),0);
 addKnowledge(s.universe,"heat",1000);
 assert.equal(knowledgeLevel(s.universe,"heat"),100);
});
test("core requires genuine stats and two understood phenomena",()=>{
 const s=createState(now);s.universe.unlocked=true;createPlanet(s,now);
 const p=planet(s);
 p.stats.energy="2000";p.stats.pressure="1000";p.stats.temperature="1000";
 assert.equal(coreRequirements(p,s.universe).ok,false);
 s.universe.knowledge.heat=100;s.universe.knowledge.pressure=100;
 assert.equal(coreRequirements(p,s.universe).ok,true);
 assert.equal(startCore(s).ok,false);
 s.universe.resources.UR6_01="1";
 assert.equal(startCore(s).ok,true);
 assert.equal(A(s.universe.resources.UR6_01).toNumber(),0);
 assert.equal(p.core.started,true);
 assert.equal(startCore(s).ok,false);
});
test("construction time does not retroactively count as pulses",()=>{
 const p={stats:{energy:"2000",pressure:"1000",temperature:"1000"},core:makeCoreState({started:true})};
 const u={knowledge:{heat:100,pressure:100}};
 const messages=[];
 let report=advanceCore(p,u,1800,x=>messages.push(x));
 assert.equal(report.formed,true);
 assert.equal(p.core.progress,100);
 assert.equal(p.core.pulses,0);
 report=advanceCore(p,u,300,x=>messages.push(x));
 assert.equal(report.pulses,5);
 assert.equal(p.core.surfaceCount,1);
 assert.equal(messages.length>=2,true);
});
test("life follows unknown state, self-maintenance and reproduction",()=>{
 const p={stats:{energy:"2000",pressure:"1000",temperature:"1000"},core:makeCoreState({formed:true,progress:100})};
 const u={knowledge:{heat:100,pressure:100}};
 let r=advanceCore(p,u,900);
 assert.equal(p.core.pulses,15);
 assert.equal(p.core.lifeStage,1);
 r=advanceCore(p,u,6000);
 assert.equal(p.core.lifeStage,2);
 r=advanceCore(p,u,900);
 assert.equal(p.core.lifeStage,3);
 assert.equal(r.life,true);
 assert.equal(u.knowledge.pulse,100);
});
test("automatic generation requires 20 collapses, five slots, understanding",()=>{
 const s=createState(now);s.universe.unlocked=true;s.lastWall=now;
 assert.equal(toggleAutoPlanet(s).ok,false);
 s.universe.collapseCount=20;s.universe.maxPlanets=5;s.universe.knowledge.collapse=100;
 assert.equal(autoPlanetAvailable(s.universe),true);
 s.universe.resources.UR1_01="500";
 assert.equal(setAutoPlanetReserve(s,10).ok,true);
 assert.equal(toggleAutoPlanet(s).ok,true);
 advance(s,now+300000,{rng:()=>.999999});
 assert.equal(s.universe.planets.length,1);
 assert.equal(A(s.universe.resources.UR1_01).toNumber(),400);
 assert.equal(s.universe.autoReserve,10);
});
test("autogeneration resource shortage never creates planet",()=>{
 const s=createState(now);s.universe.unlocked=true;s.universe.collapseCount=20;
 s.universe.maxPlanets=5;s.universe.knowledge.collapse=100;s.lastWall=now;
 s.universe.resources.UR1_01="109";setAutoPlanetReserve(s,10);
 toggleAutoPlanet(s);
 advance(s,now+300000,{rng:()=>.999999});
 assert.equal(s.universe.planets.length,0);
 assert.equal(A(s.universe.resources.UR1_01).toNumber(),109);
});
test("older v31 state gains new fields without clearing progress",()=>{
 const s=createState(now);s.universe.unlocked=true;createPlanet(s,now);
 const p=planet(s);p.stats.mass="1e5";
 delete s.universe.knowledge;delete s.universe.autoReserve;
 delete p.core;
 const normalized=validateState(s,"normal");
 assert.deepEqual(normalized.universe.knowledge,{});
 assert.equal(normalized.universe.autoReserve,0);
 assert.equal(normalized.universe.planets[0].core.formed,false);
 assert.equal(A(normalized.universe.planets[0].stats.mass).toNumber(),100000);
 assert.equal(decode(encode(normalized,"core-qa"),"normal").mode,"normal");
});
console.log("PASS "+checks+" core, life, autogeneration and v31 migration checks");
