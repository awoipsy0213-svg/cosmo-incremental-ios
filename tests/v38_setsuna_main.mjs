import assert from "node:assert/strict";
import {A} from "../numbers.mjs";
import {CONTENT} from "../content.mjs";
import {CONFIG} from "../balance-config.mjs";
import * as G from "../game.mjs";
import {encode,decode,KEYS,SaveStore} from "../save.mjs";
const start=1795000000000;
let checks=0;
function ok(v,m){assert.ok(v,m);checks++;}
function eq(a,b,m){assert.deepEqual(a,b,m);checks++;}
function fresh(){const s=G.createState(start);s.intro.complete=true;return s;}
const ids=CONTENT.moment.map(x=>x.id);
eq(ids.length,30,"30 item entries");
eq(new Set(ids).size,30,"unique internal IDs");
eq(new Set(CONTENT.moment.map(x=>x.name)).size,30,"unique effects");
eq(new Set(CONTENT.moment.map(x=>x.group)).size,6,"six effect groups");
eq(CONFIG.schemaVersion,31,"save schema unchanged");
eq(KEYS.normal,"kotowari_v31_normal","key unchanged");
const old=fresh();old.moment={tap:5,tap2:3,tap3:2,tap4:1,tap5:4,amplify:7};delete old.momentRuntime;
const restored=G.validateState(old,"normal");
for(const [id,n] of Object.entries(old.moment))eq(restored.moment[id],n,"legacy level "+id);
eq(Object.keys(restored.moment).length,30,"24 new zero levels");
eq(restored.moment.setsuna30,0,"last level initialized");
eq(decode(encode(restored),"normal").moment.amplify,7,"save roundtrip");
const pre=fresh();const base=G.tapPower(pre);
const first=fresh();first.moment.tap=4;ok(G.tapPower(first).cmp(base)>0,"I adds tap");
const source=fresh();source.sources.SOURCE_01.level=3;source.moment.setsuna21=50;
ok(G.tapPower(source).cmp(G.tapPower(pre))>0,"source to setsuna");
const combo=fresh();combo.moment.setsuna07=5;
const a=G.tap(combo,start+1000,()=>.9),b=G.tap(combo,start+1100,()=>.9);
ok(A(b.gain).cmp(a.gain)>0,"combo grows");
const crit=fresh();crit.moment.setsuna11=5000;crit.moment.setsuna12=10;
ok(A(G.tap(crit,start+1000,()=>.999).gain).cmp(1)>0,"crit over 100%");
const supply=fresh();supply.sources.SOURCE_01.level=4;supply.moment.setsuna22=80;
const rate=G.production(supply,start);
for(let i=0;i<10;i++)G.tap(supply,start+1000+i*100,()=>.99);
ok(G.production(supply,start+2300).cmp(rate)>0,"setsuna to source");
const auto=fresh();auto.moment.setsuna16=10;G.advance(auto,start+10000);
ok(A(auto.orbs).cmp(0)>0,"autonomous tap");
const release=fresh();release.moment.setsuna24=15;release.orbs="1e8";
G.tap(release,start+1000,()=>.99);
ok(release.momentRuntime.flowQueue.length>0,"queued payout");
ok(G.converge(release).ok,"convergence");
eq(release.momentRuntime.flowQueue.length,0,"queued payout resets");
for(const id of ids)eq(release.moment[id],0,"reset "+id);
const offline=fresh();offline.moment.setsuna16=20;
const ts=offline.lastWall+10800000;G.advance(offline,ts,{offline:true});
const saved=offline.orbs;G.advance(offline,ts,{offline:true});
eq(offline.orbs,saved,"no offline double payout");
const huge=fresh();huge.purchaseMode="MAX";huge.orbs="1e10000";
for(const id of ids)ok(G.purchaseQuote(huge,"moment",id).count>=0,"huge MAX "+id);
const storage=new Map(),mem={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const legacy=fresh();delete legacy.momentRuntime;
const normal=new SaveStore(mem,"normal","test");mem.setItem(KEYS.normal,encode(legacy,"old-writer"));
const loaded=normal.load(start);
ok(!!loaded.state.momentRuntime,"runtime migrated");
ok(!!mem.getItem(KEYS.normal+".before-setsuna38"),"original backup before migration");
console.log("PASS "+checks+" Setsuna30 main integration and migration checks");
