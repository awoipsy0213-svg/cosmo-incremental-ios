import assert from "node:assert/strict";
import {CONTENT} from "../content.mjs";
import {CONFIG} from "../balance-config.mjs";
import * as G from "../game.mjs";
import {KEYS,encode,decode} from "../save.mjs";
let checks=0;
const eq=(actual,expected,label)=>{assert.deepEqual(actual,expected,label);checks++;};
const yes=(value,label)=>{assert.ok(value,label);checks++;};
const time=1800000000000;
const sources=CONTENT.sources.map(x=>x.id);
eq(sources.length,30,"all thirty source IDs");
const s=G.createState(time,"normal");s.intro.complete=true;s.time.unlocked=true;
eq(s.sourceCycle,{reached:[],unlocked:false},"new save cycle shape");
eq(G.sourceCycleStatus(s).remaining,30,"initial cycle remaining 30");
const max=CONFIG.confirmed.sourceMaxLevel;
const first=sources[0],single=G.createState(time,"normal");
single.intro.complete=true;single.time.unlocked=true;
single.sources[first].level=max-1;
eq(G.sourceBreakthroughReady(single,first),false,"under cap cannot cycle");
const denial=G.breakthrough(single,first);
eq(denial.ok,false,"premature breakthrough rejected");
eq(single.sources[first].plus,0,"denial preserves plus");
eq(single.sources[first].level,max-1,"denial preserves level");
single.sources[first].level=max;
eq(G.sourceBreakthroughReady(single,first),true,"first source alone can cycle");
eq(G.breakthrough(single,first).ok,true,"individual first breakthrough");
eq(single.sources[first].plus,1,"individual plus");
eq(single.sources[first].level,1,"individual reset");
eq(G.sourceCycleStatus(single).reached,1,"one achievement retained");
eq(G.sourceCycleStatus(single).unlocked,false,"not all thirty achieved");
const earlySaved=decode(encode(single),"normal");
eq(earlySaved.sources[first].plus,1,"individual plus survives save");
eq(earlySaved.sourceCycle.reached,[first],"individual achievement survives save");
single.sources[first].level=max;
eq(G.breakthrough(single,first).plus,2,"second cycle still independent");
single.sources[first].level=max;single.sources[first].plus=1000000;
const capped=JSON.stringify(single);
eq(G.breakthrough(single,first).ok,false,"plus cap guarded");
eq(JSON.stringify(single),capped,"cap denial is not a mutation");
single.time.unlocked=false;
eq(G.sourceBreakthroughReady(single,first),false,"locked stage cannot cycle");
for(const id of sources.slice(0,29)){s.sources[id].level=max;}
eq(G.sourceCycleStatus(s).reached,29,"29/30 identified without writing");
eq(G.sourceCycleStatus(s).unlocked,false,"29/30 not yet full achievement");
s.sources[sources[29]].level=max;
eq(G.sourceCycleStatus(s).unlocked,true,"all 30 max achievement");
eq(G.sourceCycleStatus(s).remaining,0,"all reached");
const completed=G.breakthrough(s,sources[0]);
eq(completed.ok,true,"normal mode breakthrough enabled");
eq(completed.plus,1,"plus increment once");
eq(s.sources[sources[0]].level,1,"source resets to Lv1 after cycle");
eq(s.sourceCycle.unlocked,true,"unlock flag persisted");
eq(s.sourceCycle.reached.length,30,"history records all thirty");
s.sources[sources[0]].effects=["effect-one"];
eq(G.breakthrough(s,sources[0]).ok,false,"cannot repeat breakthrough before next max level");
s.sources[sources[0]].level=max;
const second=G.breakthrough(s,sources[0]);
eq(second.ok,true,"subsequent individual cycle allowed");
eq(s.sources[sources[0]].plus,2,"plus increments on second cycle");
eq(s.sources[sources[0]].effects,["effect-one","final:SOURCE_01"],"existing effect preserved and final unlocked once");
const beforeProduction=G.sourceProduction(s,sources[0]).toString();
eq(G.sourceNextGain(s,sources[0]).cmp(0)>0,true,"production remains valid when plus is owned");
eq(G.sourceCycleStatus(s).unlocked,true,"unlocked after level resets");
const serialized=decode(encode(s),"normal");
eq(serialized.sourceCycle.unlocked,true,"unlock roundtrip");
eq(serialized.sourceCycle.reached.length,30,"history roundtrip");
eq(serialized.sources[sources[0]].plus,2,"plus roundtrip");
eq(serialized.sources[sources[0]].effects,["effect-one","final:SOURCE_01"],"effects roundtrip");
const legacy=G.createState(time,"normal");
delete legacy.sourceCycle;
legacy.sources[sources[0]].plus=1;
legacy.sources[sources[1]].level=max;
const oldSaved=decode(encode(legacy),"normal");
eq(oldSaved.sourceCycle.reached,[sources[0],sources[1]],"old save infers only backed-up max or plus evidence");
eq(oldSaved.sourceCycle.unlocked,false,"old 2/30 not unlocked");
eq(oldSaved.sources[sources[0]].plus,1,"legacy + preserved");
const bad=G.createState(time,"normal");
bad.sourceCycle={reached:[sources[0],sources[0]],unlocked:false};
assert.throws(()=>G.validateState(bad,"normal"),/一巡履歴/);checks++;
const badUnlock=G.createState(time,"normal");
badUnlock.sourceCycle={reached:[sources[0]],unlocked:true};
assert.throws(()=>G.validateState(badUnlock,"normal"),/一巡達成/);checks++;
const forged=G.createState(time,"normal");
forged.sourceCycle={reached:["invalid-id"],unlocked:false};
assert.throws(()=>G.validateState(forged,"normal"),/一巡履歴/);checks++;
const normalized=G.validateState(s,"normal");
eq(normalized.sourceCycle.unlocked,true,"fully unlocked state passes validator");
const retention=G.createState(time,"normal");retention.intro.complete=true;
retention.sourceCycle={reached:[...sources],unlocked:true};
retention.sources[sources[0]].plus=3;retention.sources[sources[0]].effects=["old-effect"];
retention.sources[sources[0]].level=100;
G.addOrbs(retention,"1e100");
const cv=G.converge(retention);
yes(cv.ok,"convergence succeeds");
eq(retention.sources[sources[0]].level,0,"ordinary source level reset on convergence");
eq(retention.sources[sources[0]].plus,3,"permanent plus survives convergence");
eq(retention.sources[sources[0]].effects,["old-effect"],"unlocked effects survive convergence");
eq(retention.sourceCycle.unlocked,true,"cycle unlocked after convergence");
eq(retention.sourceCycle.reached.length,30,"all reached IDs survive convergence");
eq(CONFIG.schemaVersion,31,"save schema unchanged");
eq(KEYS.normal,"kotowari_v31_normal","save key unchanged");
console.log("PASS "+checks+" v3.14 source 30-first-pass unlock, plus, save and convergence regression");
