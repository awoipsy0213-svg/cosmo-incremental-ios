import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import * as G from "../game.mjs";
import {A} from "../numbers.mjs";
import {CONFIG} from "../balance-config.mjs";
import {engravingPrice,engravingPurchaseQuote,engravingUnlocked} from "../engraving-rules-v317.mjs";
import {encode,decode} from "../save.mjs";

const NOW=1800000000000;
const fresh=(mode="normal")=>{const s=G.createState(NOW,mode);s.intro.complete=true;return s;};
const s=fresh();
assert.equal(CONFIG.provisional.convergence.baseCost,1000000);
assert.equal(G.timeUnlockProgress(s).remaining,"1e6");
assert.equal(engravingUnlocked(s),false);
s.orbs="1e100";s.totalOrbs="1e100";s.surplusExistence="1";
assert.equal(G.purchaseQuote(s,"source","SOURCE_01","1").enabled,false);
assert.equal(G.buy(s,"source","SOURCE_01").ok,false);
assert.equal(G.buyAll(s,"source").ok,false);
assert.equal(engravingPurchaseQuote(s,"ENG-05").ok,false);
assert.equal(G.converge(s).ok,false);
assert.equal(G.checkTimeUnlock(s,NOW),false,"wallet and lifetime total never unlock");
G.addOrbs(s,999999);
assert.equal(s.time.unlocked,false);
assert.equal(A(G.timeUnlockProgress(s).remaining).cmp(1),0);
assert.equal(G.convergenceQuote(s).steps,0);
G.addOrbs(s,1);
assert.equal(s.time.unlocked,true);
assert.equal(G.timeUnlockProgress(s).remaining,"0");
assert.equal(G.convergenceQuote(s).steps,1);
assert.equal(engravingUnlocked(s),false);
assert.equal(G.buy(s,"source","SOURCE_01").ok,true);
assert.equal(G.convergenceQuote(s).steps,1,"spending does not reduce run earnings");
assert.equal(G.converge(s).ok,true);
assert.equal(s.runOrbsEarned,"0");
assert.equal(s.time.unlocked,true);
assert.equal(engravingUnlocked(s),true);
assert.equal(engravingPrice("ENG-05"),"0.05");
assert.equal(engravingPrice("ENG-01"),"0.001");
assert.equal(engravingPrice("ENG-11"),"0.025");
assert.equal(engravingPrice("ENG-21"),"0.125");
s.surplusExistence="0.049";
assert.equal(G.buyEngraving(s,"ENG-05").ok,false);
s.surplusExistence="0.05";
assert.equal(G.buyEngraving(s,"ENG-05").ok,true);
assert.equal(s.surplusExistence,"0");
assert.equal(G.engravingTrialUpgradeQuote(s,"ENG-05").ok,false);
G.addOrbs(s,10000);
assert.equal(G.buyAll(s,"moment").ok,true);
const restored=decode(encode(s,"v354"),"normal");
assert.equal(restored.time.unlocked,true);
assert.equal(engravingUnlocked(restored),true);
assert.equal(restored.engraving.owned.includes("ENG-05"),true);
const legacy=fresh();legacy.sources.SOURCE_01.level=1;
assert.equal(G.validateState(legacy,"normal").time.unlocked,true);
const old=fresh();old.engraving.owned=["ENG-05"];old.engraving.levels={"ENG-05":1};
assert.equal(engravingUnlocked(old),true,"existing ownership is preserved");
const lab=fresh("lab");
assert.equal(engravingUnlocked(lab),false);
assert.equal(G.labGrant(lab,"existence","0.05").ok,true);
assert.equal(engravingUnlocked(lab),true);
assert.equal(G.buyEngraving(lab,"ENG-05").ok,true);
assert.equal(G.labGrant(lab,"orbs","1000000").ok,true);
assert.equal(lab.time.unlocked,true);
const automatic=fresh();automatic.engraving.owned=["ENG-24"];automatic.engraving.levels={"ENG-24":1};
automatic.engraving.autoConverge.enabled=true;
G.addOrbs(automatic,"1e10");
assert.equal(G.autoConvergenceTick(automatic,NOW+60000,false).ok,false,"first convergence is manual");
const reset=G.createState(NOW);
assert.equal(reset.time.unlocked,false);
assert.equal(engravingUnlocked(reset),false);
// Deterministic constant-rate Setsuna-only path from new save.
// Use actual engine quotes and tap preview, not a grant to bypass the unlock.
const route=fresh();let seconds=0,buys=0;
const ids=Object.keys(CONFIG.provisional.moment);
while(!route.time.unlocked&&buys<3000){
  const q=ids.map(id=>({id,...G.purchaseQuote(route,"moment",id,"1")})).filter(x=>A(x.cost).cmp(0)>0).sort((a,b)=>A(a.cost).cmp(b.cost))[0];
  const needed=A(q.cost).sub(route.orbs),income=G.tapPower(route,NOW).mul(5);
  const until=A(G.timeUnlockProgress(route).remaining);
  const gain=needed.cmp(until)>0?until:needed;
  const dt=gain.div(income).toNumber();
  assert.ok(Number.isFinite(dt)&&dt>=0);
  seconds+=dt;G.addOrbs(route,gain);
  if(route.time.unlocked)break;
  if(A(route.orbs).cmp(q.cost)<0)G.addOrbs(route,A(q.cost).mul(1e-12));
  assert.equal(G.buy(route,"moment",q.id).ok,true);buys++;
}
assert.equal(route.time.unlocked,true);
assert.ok(Object.values(route.sources).every(x=>x.level===0));
console.log("V354 initial route seconds",Math.round(seconds),"purchases",buys);
for(const p of ["balance-config.mjs","game.mjs","app.mjs","engraving-rules-v317.mjs","fixed-layout-v333.css","index.html","sw.js"])
  assert.equal(readFileSync(new URL("../"+p,import.meta.url),"utf8"),readFileSync(new URL("../www/"+p,import.meta.url),"utf8"));
console.log("PASS v354 unlock boundary, locked purchases, first convergence, ENG-05 cost, old saves and test isolation");
