import assert from "node:assert/strict";
import {CONTENT} from "../content.mjs";
import {CONFIG} from "../balance-config.mjs";
import {A} from "../numbers.mjs";
import * as G from "../game.mjs";
import * as L from "../price-lab.mjs";
import * as F from "../moment-filter.mjs";
import {KEYS,encode,decode} from "../save.mjs";
let checks=0;
const eq=(a,b,m)=>{assert.deepEqual(a,b,m);checks++};
const yes=(a,m)=>{assert.ok(a,m);checks++};
const throws=(f,m)=>{assert.throws(f,m);checks++};
const now=1800000000000,s=G.createState(now,"normal");
s.intro.complete=true;s.orbs="1e20";s.moment.tap=9;
const original=JSON.stringify(s),originalBalance=JSON.stringify(CONFIG.provisional.moment);
yes(["3.12.0","3.13.0","3.14.0","3.15.0","3.16.0","3.17.0","3.18.0","3.19.0","3.20.0","3.21.0","3.22.0","3.23.0","3.24.0","3.25.0","3.26.0","3.27.0","3.30.1"].includes(CONFIG.version),"v3.12 features retained in current release");
eq(CONFIG.schemaVersion,31,"save schema unchanged");
eq(KEYS.normal,"kotowari_v31_normal","normal save key unchanged");
eq(L.PRICE_MODEL_VERSION,"3.12.0-approx","trial model version");
const defaultReport=L.compareMomentPrice(s,{momentId:"tap",now});
eq(defaultReport.priceCandidates.length,3,"default candidate count");
eq(defaultReport.priceCandidates.map(c=>c.factor),[.5,1,2],"default factors");
eq(defaultReport.priceCandidates[1].trialPriceDifferencePercent,0,"base price difference");
eq(defaultReport.priceCandidates[0].trialPriceDifferencePercent,-50,"-50 percent");
eq(defaultReport.priceCandidates[2].trialPriceDifferencePercent,100,"+100 percent");
const custom=L.compareMomentPrice(s,{momentId:"tap",now,factorOverride:1.25});
eq(custom.priceCandidates.map(x=>x.factor),[.5,1,1.25,2],"custom candidate sorted");
yes(A(custom.priceCandidates[2].trialPriceDifference).cmp(0)>0,"custom price delta positive");
eq(custom.priceCandidates[2].trialPriceDifferencePercent,25,"custom delta +25%");
eq(L.compareMomentPrice(s,{momentId:"tap",now,factorOverride:1}).priceCandidates.length,3,"no duplicate factor");
const low=L.compareMomentPrice(s,{momentId:"tap",now,factorOverride:.01});
eq(low.priceCandidates[0].factor,.01,"lower input boundary");
const high=L.compareMomentPrice(s,{momentId:"tap",now,factorOverride:1000});
eq(high.priceCandidates.at(-1).factor,1000,"upper input boundary");
for(const factorOverride of [-1,0,.001,1001,Number.POSITIVE_INFINITY,Number.NaN,"3",{},[]])
 throws(()=>L.compareMomentPrice(s,{momentId:"tap",now,factorOverride}),"invalid factor rejected");
const trio=L.compareMomentPriceProfiles(s,{momentId:"tap",profiles:["early","middle","late"],now});
eq(trio.length,3,"three profile comparisons");
eq(trio.map(r=>r.profile),["early","middle","late"],"profile ordering");
yes(trio.every(r=>r.priceStatus.includes("未確定")),"trial price unconfirmed");
yes(trio.every(r=>r.modelVersion===L.PRICE_MODEL_VERSION),"trial model declared");
yes(trio.every(r=>r.excludedEffects.length>=3),"unmeasured effects reported");
eq(L.compareMomentPriceProfiles(s,{momentId:"tap",profiles:["current"],now}).length,1,"single-profile mode");
for(const profiles of [[],["early","middle","late","current"],["early","early"],["none"],null])
 throws(()=>L.compareMomentPriceProfiles(s,{momentId:"tap",profiles,now}),"invalid profiles rejected");
const exported=JSON.parse(L.exportPriceReport(trio,{createdAt:"2026-11-19T00:00:00Z"}));
eq(exported.type,"kotowari-trial-price-report","report marker");
eq(exported.formatVersion,1,"report version");
eq(exported.reports.length,3,"three reports exported");
eq(exported.modelVersion,L.PRICE_MODEL_VERSION,"report model included");
yes(exported.warning.includes("正式"),"report warns trial only");
yes(!("sources" in exported)&&!("orbs" in exported),"no saved player state in export");
eq(JSON.parse(L.exportPriceReport(custom,{createdAt:"2026-11-19T00:00:00Z"})).reports.length,1,"single report");
for(const r of [[],[custom,custom,custom,custom],{},null])
 throws(()=>L.exportPriceReport(r),"reject invalid export");
eq(JSON.stringify(s),original,"no live save mutated");
eq(JSON.stringify(CONFIG.provisional.moment),originalBalance,"no official prices modified");
const s2=decode(encode(s),"normal");
eq(s2.moment.tap,9,"normal save migration preserved");
const item={id:CONTENT.moment[0].id,name:CONTENT.moment[0].name,description:CONTENT.moment[0].description+" 手動タップを増加",group:0,affordable:true};
yes(F.momentVisible(item,{group:"all",filter:"all",search:"原初 接触"}),"all keyword match");
yes(!F.momentVisible(item,{group:"all",filter:"all",search:"原初 放射"}),"all words required");
yes(F.momentVisible(item,{group:"all",filter:"all",search:"原初  タップ"}),"multiple spaces supported only where text includes matching term");
console.log("PASS "+checks+" Ver.3.12 price comparisons, export, bounds, old saves and search");
