import assert from "node:assert/strict";
import * as G from "../game.mjs";
import {CONTENT} from "../content.mjs";
import {CONFIG} from "../balance-config.mjs";
import {A,seriesCost} from "../numbers.mjs";
import {KEYS,encode,decode} from "../save.mjs";
let checks=0;
const ok=(value,label)=>{assert.ok(value,label);checks++};
const equal=(a,b,label)=>{assert.deepEqual(a,b,label);checks++};
const when=1800000000000;
equal(G.MAX_LEVELS_PER_ACTION,3000,"U-06 per-action MAX cap");
const current=G.createState(when,"normal");current.intro.complete=true;
const price=CONFIG.provisional.moment.tap;
current.orbs=seriesCost(price.baseCost,price.growth,0,3005).toString();
current.purchaseMode="MAX";
const first=G.purchaseQuote(current,"moment","tap");
equal(first.count,3000,"individual MAX stops at exactly 3000");
ok(first.limitReached,"warn when more affordable levels exist");
const oldLevel=current.moment.tap,oldWallet=current.orbs;
const result=G.buy(current,"moment","tap");
ok(result.ok,"MAX purchase works");
equal(current.moment.tap-oldLevel,3000,"buy applies bounded quote");
equal(result.count,3000,"returned purchase count");
ok(A(current.orbs).cmp(A(oldWallet))<=0,"wallet never grows on purchase");
const again=G.purchaseQuote(current,"moment","tap");
ok(again.count>0&&again.count<3000,"can continue MAX explicitly");
const completed=G.buy(current,"moment","tap");
ok(completed.ok&&completed.count===again.count,"second explicit MAX call buys remaining levels");
const noMore=G.purchaseQuote(current,"moment","tap");
ok(noMore.count<=3000,"all later MAX quotes bounded");
const unchanged=G.createState(when,"normal");unchanged.intro.complete=true;
unchanged.orbs="100000";unchanged.purchaseMode="NEXT";
equal(G.purchaseQuote(unchanged,"source",CONTENT.sources[0].id).count,25,"NEXT still seeks next source milestone");
unchanged.purchaseMode="10";equal(G.purchaseQuote(unchanged,"moment","tap").count,10,"x10 behavior unchanged");
unchanged.purchaseMode="1";equal(G.purchaseQuote(unchanged,"moment","tap").count,1,"x1 behavior unchanged");
equal(G.maxPurchaseRequiresConfirmation("1000",{cost:"900",enabled:true},"MAX"),true,"confirm at 90 percent");
equal(G.maxPurchaseRequiresConfirmation("1000",{cost:"899",enabled:true},"MAX"),false,"no confirm below 90 percent");
equal(G.maxPurchaseRequiresConfirmation("1000",{cost:"1000",enabled:true},"MAX"),true,"confirm at 100 percent");
equal(G.maxPurchaseRequiresConfirmation("1000",{cost:"900",enabled:false},"MAX"),false,"disabled quote no confirm");
equal(G.maxPurchaseRequiresConfirmation("1000",{cost:"900",enabled:true},"NEXT"),false,"NEXT does not use MAX confirm");
equal(G.maxPurchaseRequiresConfirmation("0",{cost:"0",enabled:true},"MAX"),false,"zero wallet no confirm");
const saved=G.createState(when,"normal");saved.intro.complete=true;saved.moment.tap=30;
equal(decode(encode(saved),"normal").moment.tap,30,"save migration untouched");
equal(KEYS.normal,"kotowari_v31_normal","normal save key unchanged");
equal(CONFIG.schemaVersion,31,"schema stays 31");
console.log("PASS "+checks+" v3.13 U-06 MAX 3000 and U-09 90pct confirmation regression checks");
