import assert from "node:assert/strict";
import {CONTENT} from "../content.mjs";
import {CONFIG} from "../balance-config.mjs";
import * as M from "../moment-filter.mjs";
import * as G from "../game.mjs";
import {KEYS,encode,decode} from "../save.mjs";
let checks=0;
const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);checks++};
const yes=(a,msg)=>{assert.ok(a,msg);checks++};
const ids=CONTENT.moment.map(x=>x.id);
eq(ids.length,30,"moment entry count");
eq(M.MOMENT_GROUP_NAMES.length,6,"six groups");
eq(CONFIG.version,"3.10.0","release version");
eq(CONFIG.schemaVersion,31,"save format untouched");
eq(KEYS.normal,"kotowari_v31_normal","normal data key unchanged");
const initial=G.createState(1800000000000);
const settings=initial.settings;
eq(settings.momentFavorites,[],"new save favorites empty");
eq(settings.momentGroup,"0","initial group");
eq(settings.momentFilter,"all","initial filter");
const valid=M.cleanMomentPrefs({momentFavorites:[ids[0],ids[1],ids[0],"strange",...ids.slice(2,10)],momentGroup:"5",momentFilter:"favorites"},ids);
eq(valid.momentFavorites,ids.slice(0,5),"dedupe, clip, discard invalid IDs");
eq(valid.momentGroup,"5","group is persisted");
eq(valid.momentFilter,"favorites","filter is persisted");
eq(M.cleanMomentPrefs({momentFavorites:"not an array",momentGroup:"99",momentFilter:"wrong"},ids).momentFavorites,[],"corrupt preferences restored");
eq(M.cleanMomentPrefs({momentGroup:"not",momentFilter:"wrong"},ids).momentGroup,"0","invalid group cleared");
eq(M.cleanMomentPrefs({momentGroup:"all"},ids).momentGroup,"all","all groups supported");
let f=[];
for(const id of ids.slice(0,5)){
 const r=M.toggleMomentFavorite(f,id,ids);
 yes(r.changed,"favorites accepted until five");f=r.favorites;
}
eq(f.length,5,"five favorites");
eq(M.toggleMomentFavorite(f,ids[5],ids).error,"limit","sixth favorite rejected");
eq(M.toggleMomentFavorite(f,"not-in-content",ids).error,"invalid","unknown favorite rejected");
eq(M.toggleMomentFavorite(f,ids[2],ids).favorites,[ids[0],ids[1],ids[3],ids[4]],"toggle off existing favorite");
const entry={id:ids[0],name:"Ⅰ 原初の接触",description:"基本タップを増加",group:0,affordable:false};
yes(M.momentVisible(entry,{group:"0",filter:"all"}),"same group visible");
yes(!M.momentVisible(entry,{group:"1",filter:"all"}),"other group hidden");
yes(M.momentVisible(entry,{group:"all",filter:"all"}),"all groups shown");
yes(M.momentVisible(entry,{group:"4",filter:"all",search:"原初"}),"search crosses group");
yes(M.momentVisible(entry,{group:"5",filter:"all",search:"タップ"}),"search finds description");
yes(!M.momentVisible(entry,{group:"all",filter:"all",search:"別の名前"}),"search narrows");
yes(!M.momentVisible(entry,{group:"all",filter:"affordable"}),"unaffordable hidden");
yes(M.momentVisible({...entry,affordable:true},{group:"all",filter:"affordable"}),"affordable shown");
yes(!M.momentVisible(entry,{group:"all",filter:"favorites",favorites:[]}),"not favorite hidden");
yes(M.momentVisible(entry,{group:"all",filter:"favorites",favorites:[ids[0]]}),"favorite visible");
const migrated=G.validateState(initial,"normal");
eq(migrated.settings.momentFavorites,[],"current save validated");
const old=G.createState(1800000000000);
delete old.settings.momentFavorites;delete old.settings.momentGroup;delete old.settings.momentFilter;
const restored=G.validateState(old,"normal");
eq(restored.settings.momentGroup,"0","pre-3.10 save gets default group");
eq(restored.settings.momentFavorites,[],"pre-3.10 save retains all game progress");
const own=G.createState(1800000000000);
own.intro.complete=true;own.moment.tap=13;own.orbs="1e8";
own.settings.momentFavorites=ids.slice(0,5);own.settings.momentGroup="all";own.settings.momentFilter="favorites";
const recovered=decode(encode(own),"normal");
eq(recovered.moment.tap,13,"favorite UI does not affect levels");
eq(recovered.settings.momentFavorites,ids.slice(0,5),"favorites roundtrip in normal save");
eq(recovered.settings.momentGroup,"all","selected group roundtrip");
eq(recovered.settings.momentFilter,"favorites","filter roundtrip");
yes(G.converge(own).ok,"convergence");
eq(own.settings.momentFavorites,ids.slice(0,5),"favorites survive convergence");
eq(own.settings.momentGroup,"all","selected group survives convergence");
const available=G.createState(1800000000000);available.intro.complete=true;
eq(G.purchaseQuote(available,"moment",ids[0]).enabled,false,"wallet shortage remains");
available.orbs="1e10";
yes(G.purchaseQuote(available,"moment",ids[0]).enabled,"purchase ability unchanged");
console.log("PASS "+checks+" v3.10 purchase navigation, validation, migration and save checks");
